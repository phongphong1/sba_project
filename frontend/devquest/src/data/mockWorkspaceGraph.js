export const DEFAULT_WORKSPACE_ID = MOCK_WORKSPACES[0]?.id ?? null
export const HAS_WORKSPACES = MOCK_WORKSPACES.length > 0

export const DEFAULT_BOARD_IDS = Object.fromEntries(
  MOCK_WORKSPACES.map((workspace) => [workspace.id, workspace.boards[0]?.id ?? null]),
)

export function getWorkspaceById(workspaceId) {
  return MOCK_WORKSPACES.find((workspace) => workspace.id === workspaceId) ?? null
}

export function getBoardById(workspaceId, boardId) {
  return getWorkspaceById(workspaceId)?.boards.find((board) => board.id === boardId) ?? null
}
